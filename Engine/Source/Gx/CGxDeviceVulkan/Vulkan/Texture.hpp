// Images: create them, record their fills (region uploads, clears, generated mip chains) into a
// command buffer the frame submits, and destroy them.
#pragma once

#include "Engine/Source/Gx/CGxDeviceVulkan/Vulkan/Memory.hpp"
#include "Engine/Source/Gx/CGxDeviceVulkan/Vulkan/Vk.hpp"

#include <cstddef>
#include <cstdint>

// Every image is OPTIMAL-tiled, TRANSFER_DST | TRANSFER_SRC | SAMPLED (plus an attachment usage for
// a render target), with a view made at creation. Nothing here submits: every fill is RECORDED into
// a command buffer the caller owns (the frame's pre-pass buffer, or its main buffer outside the
// render pass), and the frame's submit carries it. Init() after memory::Init(): every image's
// memory is a memory::Block.
//
// Ownership: this module owns the images it creates; the caller's Image is a view of one of them.
// DestroyIdle() of an image this module does not hold is recognised and does nothing.
//
// Single-threaded by contract, like everything under Vulkan/.
namespace gxvk::vk::texture
{
    /// One image, with the layout it is currently in.
    struct Image
    {
        VkImage        handle = VK_NULL_HANDLE;
        /// A view of every level and every layer, in the image's own format: VIEW_TYPE_2D for a 2D
        /// image, VIEW_TYPE_CUBE for a cube map. What a descriptor binds.
        VkImageView    view   = VK_NULL_HANDLE;
        /// This module's own number for the image, from 1 up, never given twice in a session: what
        /// a per-frame descriptor cache keys an image by, since a destroyed image's handles are
        /// reused by the driver and its id is not. 0: not made here.
        uint32_t       id     = 0;
        memory::Block  block;
        VkFormat       format = VK_FORMAT_UNDEFINED;
        VkExtent2D     extent = { 0, 0 };                   ///< of mip level 0
        uint32_t       levels = 1;
        uint32_t       layers = 1;                          ///< 1, or 6 for a cube map
        bool           cube   = false;
        /// One layout for every level and layer (see WholeColour in Texture/Registry.cpp).
        VkImageLayout  layout = VK_IMAGE_LAYOUT_UNDEFINED;
    };

    /**
     * Prepares the image table and reads the limits. Idempotent. Needs a live context.
     *
     * @return bool ok : false when there is no context or an entry point is missing (logged by name)
     */
    bool Init();

    /// Forgets the device and frees the table. Every image must already have been destroyed.
    void Shutdown();

    /**
     * Creates an OPTIMAL-tiled, TRANSFER_DST | TRANSFER_SRC | SAMPLED 2D image with `levels` mip
     * levels, binds DeviceLocal memory to it and creates its view. Level i has extent
     * max(1, width >> i) x max(1, height >> i). Block-compressed formats are accepted only when
     * the context reports textureCompressionBC.
     *
     * @param uint32 width, height : texels, 1 .. maxImageDimension2D
     * @param uint32 levels : 1 .. floor(log2(max(width, height))) + 1
     * @param VkFormat format : one Describe() in Texture/Registry.cpp knows
     * @param Image& out : must be zeroed; receives the image in VK_IMAGE_LAYOUT_UNDEFINED
     * @return bool ok : on failure nothing is left created and `out` is untouched
     */
    bool CreateMipped(uint32_t width, uint32_t height, uint32_t levels, VkFormat format, Image& out);

    /**
     * A cube map: as CreateMipped(size, size, ...) with six array layers, CUBE_COMPATIBLE and a
     * cube view. Layer order is the API's (+X, -X, +Y, -Y, +Z, -Z), the same as D3D9's
     * D3DCUBEMAP_FACES, so face i uploads into layer i.
     */
    bool CreateCube(uint32_t size, uint32_t levels, VkFormat format, Image& out);

    /**
     * A render target: CreateMipped / CreateCube plus COLOR_ATTACHMENT usage (the format's
     * COLOR_ATTACHMENT feature checked first).
     */
    bool CreateTarget(uint32_t width, uint32_t height, uint32_t levels, bool cube, VkFormat format, Image& out);

    /**
     * The tightly packed size of a region of `img`'s format: bytes per row (per block row for a BC
     * format) and the row count. What RecordRegions() expects its source to hold.
     *
     * @return bool ok : false for a format this module does not describe or an empty region
     */
    bool RegionBytes(const Image& img, uint32_t width, uint32_t height, uint64_t& rowBytes, uint32_t& rowCount);

    /**
     * Destroys the view, then the image, and frees its block, for a caller that has PROVEN the GPU
     * is done with the image (the frame retires images by serial). No device wait.
     *
     * @param Image& img : zeroed on return
     */
    void DestroyIdle(Image& img);

    /**
     * Whether an image of this format can have its mip chain generated by RecordGenerateMips():
     * optimal tiling with BLIT_SRC, BLIT_DST and linear filtering, not block-compressed.
     */
    bool CanGenerateMips(VkFormat format);

    /// One region of a batched upload: level, origin and extent in texels, the layer (cube face),
    /// and the packed source's byte offset in the batch's one buffer.
    struct RegionCopy
    {
        uint32_t     level     = 0;
        uint32_t     x         = 0;
        uint32_t     y         = 0;
        uint32_t     width     = 0;
        uint32_t     height    = 0;
        uint32_t     layer     = 0;
        VkDeviceSize srcOffset = 0;
    };

    /**
     * Records a batch of region copies from one source buffer into the image, with ONE barrier
     * before (waiting for earlier sampler reads and transfers of the image, contents outside the
     * regions kept) and ONE after (to SHADER_READ_ONLY_OPTIMAL, visible to the shader stages and
     * to transfers). A region outside its level, or off the 4x4 block grid of a BC format, is left
     * out. Outside a render pass; the source buffer must live until the submission completes.
     *
     * The source is tightly packed (bufferRowLength 0): a byte pitch cannot be expressed to
     * vkCmdCopyBufferToImage, whose row length is in texels of the block grid.
     *
     * @return uint32 recorded : regions recorded; 0 when nothing was
     */
    uint32_t RecordRegions(VkCommandBuffer cmd, Image& img, VkBuffer src, const RegionCopy* regions, uint32_t count);

    /**
     * Records a clear of every level and layer to one colour (opaque mid grey by default), from
     * UNDEFINED (the contents are discarded), ending in SHADER_READ_ONLY_OPTIMAL. A VkImage is born
     * with undefined contents, and a level the engine never uploads would otherwise sample as VRAM.
     *
     * @param const float* rgba : the colour; null for opaque mid grey
     */
    bool RecordClear(VkCommandBuffer cmd, Image& img, const float* rgba = nullptr);

    /**
     * Records the mip chain derived from level 0 (D3D9's AUTOGENMIPMAP after a level-0 update): a
     * linear vkCmdBlitImage per level, every layer at once, with the barriers between levels. The
     * first barrier waits for every earlier sampler read and transfer write of the image; the image
     * ends in SHADER_READ_ONLY_OPTIMAL. The caller has checked CanGenerateMips(img.format).
     */
    bool RecordGenerateMips(VkCommandBuffer cmd, Image& img);

    struct Stats
    {
        uint64_t created   = 0;
        uint64_t destroyed = 0;
        uint64_t refused   = 0;   ///< creates refused (limits, format, table full, a failed call)
        uint64_t regions   = 0;   ///< region copies recorded
        uint64_t batches   = 0;   ///< RecordRegions calls that recorded something
        uint64_t clears    = 0;
        uint64_t chains    = 0;   ///< mip chains recorded
        uint32_t live      = 0;
        uint32_t livePeak  = 0;
        uint64_t bytes     = 0;   ///< device memory asked for, summed over creates
    };
    void GetStats(Stats& out);
}
