"""Compiles the GLSL under this folder to SPIR-V and writes the .inc files of uint32_t arrays the
backend embeds: Spirv.inc (the draw programs, Vulkan/Pipelines/Programs.cpp) and PresentSpirv.inc
(the present pass, Vulkan/Present.cpp), ParticleSpirv.inc and LightingSpirv.inc (compute).

The .inc files are committed: a build needs no glslang. Run this after editing a shader:

    python Compile.py [path/to/glslang.exe]

glslang is taken from the argument, else from GLSLANG in the environment, else from PATH. The
shaders #include Push.glsl, which glslang resolves relative to the source (-l enables the include
extension).
"""

import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUTS = [
    ("Spirv.inc", [
        ("Ff.vert", "kFfVert"),
        ("Ff.frag", "kFfFrag"),
        ("Ui.vert", "kUiVert"),
        ("Ui.frag", "kUiFrag"),
        ("Desaturate.frag", "kDesaturateFrag"),
        ("Msdf.frag", "kMsdfFrag"),
        ("FfSem.vert", "kFfSemVert"),
        ("FfTranslated.frag", "kFfTranslatedFrag"),
    ]),
    ("PresentSpirv.inc", [
        ("Present.vert", "kPresentVert"),
        ("Present.frag", "kPresentFrag"),
    ]),
    # GPUPARTICLES: the particle quad expansion (Vulkan/ParticleQuads.cpp)
    ("ParticleSpirv.inc", [
        ("ParticleQuads.comp", "kParticleQuadsComp"),
    ]),
    # LIGHTING: the modern-lighting post passes (Vulkan/Lighting.cpp)
    ("LightingSpirv.inc", [
        ("LightingAo.comp", "kLightingAoComp"),
        ("LightingBlur.comp", "kLightingBlurComp"),
        ("LightingApply.comp", "kLightingApplyComp"),
        ("LightingBloom.comp", "kLightingBloomComp"),
        ("LightingTonemap.comp", "kLightingTonemapComp"),
    ]),
]


def find_glslang():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("GLSLANG"):
        return os.environ["GLSLANG"]
    for name in ("glslang", "glslangValidator"):
        found = shutil.which(name)
        if found:
            return found
    sys.exit("glslang not found: pass its path, set GLSLANG, or put it on PATH")


def write_inc(glslang, out_name, shaders):
    names = ", ".join(source for source, _ in shaders)
    lines = [
        f"// Generated by Shaders/Compile.py from {names}: SPIR-V 1.0 for Vulkan 1.0,",
        "// as uint32_t words. Do not edit; edit the GLSL and run the script.",
        "",
    ]
    for source, symbol in shaders:
        spv = os.path.join(HERE, source + ".spv")
        subprocess.check_call([glslang, "-V", "-l", "-Os", "--target-env", "vulkan1.0", "-I" + HERE, os.path.join(HERE, source), "-o", spv])
        with open(spv, "rb") as f:
            data = f.read()
        os.remove(spv)
        if len(data) % 4:
            sys.exit(f"{source}: SPIR-V size is not a multiple of 4")
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append(f"static const uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08X" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    out = os.path.join(HERE, out_name)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")


def main():
    glslang = find_glslang()
    for out_name, shaders in OUTPUTS:
        write_inc(glslang, out_name, shaders)


if __name__ == "__main__":
    main()
