#!/usr/bin/env python3
"""Compile Lighting.hlsl to DXBC and write ../LightingShaders.h (committed: a build needs no compiler).

    python3 Lighting.py
Compiler: vkd3d-compiler from /root/d3d11-port/vkd3d-install, the one ffshaders/build.py uses.
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VKD3D = os.environ.get('VKD3D', '/root/d3d11-port/vkd3d-install')
# (name, entry, profile, defines); the order is D3d11Lighting's EShader
JOBS = [
    ('FullscreenVs', 'FullscreenVs', 'vs_4_0', {}),
    ('AoPs', 'AoPs', 'ps_4_0', {}),
    ('AoPsMs', 'AoPs', 'ps_4_1', {'GX_MSAA': 1}),
    ('BlurPs', 'BlurPs', 'ps_4_0', {}),
    ('AoCompositePs', 'AoCompositePs', 'ps_4_0', {}),
    ('AoCompositePsMs', 'AoCompositePs', 'ps_4_1', {'GX_MSAA': 1}),
    ('FogPs', 'FogPs', 'ps_4_0', {}),
    ('FogPsMs', 'FogPs', 'ps_4_1', {'GX_MSAA': 1}),
    ('BloomPrefilterPs', 'BloomPrefilterPs', 'ps_4_0', {}),
    ('BloomDownPs', 'BloomDownPs', 'ps_4_0', {}),
    ('BloomUpPs', 'BloomUpPs', 'ps_4_0', {}),
    ('TonemapPs', 'TonemapPs', 'ps_4_0', {}),
]


def main():
    gen = os.path.join(HERE, 'gen')
    os.makedirs(gen, exist_ok=True)
    lines = ['// Generated by Lighting/Lighting.py from Lighting/Lighting.hlsl. Do not edit.', '#pragma once',
             '#include <stddef.h>', '', 'struct LightingBlob { const unsigned char* data; size_t size; };', '']
    names = []
    for name, entry, profile, defines in JOBS:
        wrapper = os.path.join(gen, name + '.hlsl')
        with open(wrapper, 'w') as f:
            f.writelines(f'#define {k} {v}\n' for k, v in defines.items())
            f.write('#include "../Lighting.hlsl"\n')
        out = os.path.join(gen, name + '.dxbc')
        r = subprocess.run([os.path.join(VKD3D, 'bin/vkd3d-compiler'), '-x', 'hlsl', '-b', 'dxbc-tpf', '-p', profile,
                            '-e', entry, '-o', out, wrapper],
                           env=dict(os.environ, LD_LIBRARY_PATH=os.path.join(VKD3D, 'lib')),
                           capture_output=True, text=True, cwd=gen)
        if r.returncode or not os.path.exists(out):
            sys.exit(f'{name}: {r.stdout}{r.stderr}')
        data = open(out, 'rb').read()
        lines.append(f'static const unsigned char lighting_{name}[{len(data)}] = {{{",".join(map(str, data))}}};')
        names.append(name)
    lines += ['', 'static const LightingBlob g_lightingShaders[] = {']
    lines += [f'    {{ lighting_{n}, sizeof(lighting_{n}) }},' for n in names]
    lines += ['};', '']
    open(os.path.join(HERE, '..', 'LightingShaders.h'), 'w').write('\n'.join(lines))
    print(f'{len(names)} shaders')


main()
