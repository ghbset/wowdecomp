"""Compiles FontMsdf_ps40.hlsl (the D3D11 MSDF font shader) to DXBC and writes
../GxuFontMsdfShaders.inc, which is committed: a build needs no compiler. Run after editing it:

    python3 Compile.py [path/to/vkd3d-compiler]

vkd3d-compiler is the one shader-xlate uses (/root/d3d11-port/vkd3d-install), else VKD3D_COMPILER or PATH.
The D3D9 ps_2_a bytecode (FontMsdf_ps2a.hlsl) is tester's fxc build, kept in GxuFontMsdf.cpp; the
Vulkan shader is CGxDeviceVulkan/Shaders/Msdf.frag (its Compile.py).
"""
import os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = '/root/d3d11-port/vkd3d-install/bin/vkd3d-compiler'
cc = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('VKD3D_COMPILER') or (DEFAULT if os.path.exists(DEFAULT) else shutil.which('vkd3d-compiler'))
if not cc:
    sys.exit('vkd3d-compiler not found')
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(os.path.dirname(os.path.dirname(cc)), 'lib'))
dx = subprocess.run([cc, '-x', 'hlsl', '-p', 'ps_4_0', '-b', 'dxbc-tpf', os.path.join(HERE, 'FontMsdf_ps40.hlsl')],
                    check=True, capture_output=True, env=env).stdout
assert dx[:4] == b'DXBC', 'no DXBC out'
lines = ['// Generated by Shaders/Compile.py from FontMsdf_ps40.hlsl (vkd3d-compiler, ps_4_0). Do not edit.', '',
         'static const uint8_t s_msdfPs40Dxbc[] = {']
for i in range(0, len(dx), 16):
    lines.append('    ' + ', '.join('0x%02X' % b for b in dx[i:i + 16]) + ',')
lines += ['};', '']
with open(os.path.join(HERE, '..', 'GxuFontMsdfShaders.inc'), 'w', newline='\n') as f:
    f.write('\n'.join(lines))
print('wrote GxuFontMsdfShaders.inc, %d bytes of DXBC' % len(dx))
